"""Credential-free subprocess tests for a safe ACP fixture artifact."""

from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest


SCRIPT = Path(__file__).parent / "fixtures" / "acp_artifact_agent.py"
EXPECTED = (
    b"# Kovan ACP integration fixture\n\n"
    b"Work item: yesvus/kovan#1\n"
    b"Generated by: disposable ACP JSON-RPC test peer\n"
    b"Result: deterministic, no LLM or GitHub credentials\n"
)


def exchange(root: str, messages: list[str]):
    env = {**os.environ, "KOVAN_FIXTURE_ROOT": root}
    return subprocess.run(
        [sys.executable, str(SCRIPT)],
        input="\n".join(messages) + "\n",
        text=True,
        capture_output=True,
        check=True,
        timeout=10,
        env=env,
    )


def request(index: int, method: str) -> str:
    return json.dumps({
        "jsonrpc": "2.0",
        "id": index,
        "method": method,
        "params": {},
    })


class ACPArtifactFixtureTests(unittest.TestCase):
    def test_acp_handshake_and_prompt_produce_exact_safe_artifact(self):
        with tempfile.TemporaryDirectory() as root:
            inputs = [
                request(1, "initialize"),
                request(2, "session/new"),
                request(3, "session/prompt"),
            ]
            result = exchange(root, inputs)
            self.assertEqual(result.stderr, "")
            replies = list(map(json.loads, result.stdout.splitlines()))
            self.assertEqual(replies[0]["result"]["protocolVersion"], 1)
            self.assertEqual(
                replies[1]["result"]["sessionId"],
                "kovan-acp-artifact-fixture",
            )
            self.assertEqual(replies[2]["method"], "session/update")
            self.assertEqual(
                replies[2]["params"]["update"]["content"]["text"],
                "KOVAN_ACP_ARTIFACT_WRITTEN",
            )
            self.assertEqual(replies[3]["result"]["stopReason"], "end_turn")
            artifact = Path(root) / "pilot" / "issue-1" / "acp.md"
            self.assertEqual(artifact.read_bytes(), EXPECTED)
            self.assertEqual(
                hashlib.sha256(artifact.read_bytes()).hexdigest(),
                hashlib.sha256(EXPECTED).hexdigest(),
            )
            self.assertEqual(
                [p.relative_to(root).as_posix() for p in
                 Path(root).rglob("*") if p.is_file()],
                ["pilot/issue-1/acp.md"],
            )

    def test_unsupported_method_cannot_trigger_file_write(self):
        with tempfile.TemporaryDirectory() as root:
            result = exchange(root, [request(1, "tools/call")])
            lines = [json.loads(line) for line in result.stdout.splitlines()]
            self.assertEqual(lines[0]["error"]["code"], -32601)
            self.assertEqual(list(Path(root).iterdir()), [])

    def test_invalid_json_and_notifications_ignored(self):
        with tempfile.TemporaryDirectory() as root:
            data = ["not JSON", json.dumps({
                "jsonrpc": "2.0",
                "method": "session/prompt",
                "params": {"prompt": "execute anything"},
            })]
            result = exchange(root, data)
            self.assertEqual(result.stdout, "")
            self.assertEqual(list(Path(root).iterdir()), [])

    def test_repeat_prompt_is_idempotent(self):
        with tempfile.TemporaryDirectory() as root:
            result = exchange(
                root, [request(1, "session/prompt"), request(2, "session/prompt")]
            )
            messages = [json.loads(x) for x in result.stdout.splitlines()]
            self.assertEqual(len(messages), 4)
            self.assertEqual(
                (Path(root) / "pilot/issue-1/acp.md").read_bytes(), EXPECTED
            )

    def test_existing_different_artifact_is_not_overwritten(self):
        with tempfile.TemporaryDirectory() as root:
            target = Path(root) / "pilot/issue-1/acp.md"
            target.parent.mkdir(parents=True)
            target.write_bytes(b"untrusted prior content")
            result = exchange(root, [request(1, "session/prompt")])
            response = json.loads(result.stdout)
            self.assertEqual(response["error"]["code"], -32000)
            self.assertEqual(target.read_bytes(), b"untrusted prior content")

    def test_symlink_target_is_not_overwritten(self):
        with tempfile.TemporaryDirectory() as root:
            target = Path(root) / "pilot/issue-1/acp.md"
            target.parent.mkdir(parents=True)
            secret = Path(root) / "private.txt"
            secret.write_bytes(b"do not touch")
            target.symlink_to(secret)
            result = exchange(root, [request(1, "session/prompt")])
            self.assertEqual(json.loads(result.stdout)["error"]["code"], -32000)
            self.assertEqual(secret.read_bytes(), b"do not touch")

    def test_intermediate_symlink_is_not_followed(self):
        with tempfile.TemporaryDirectory() as root:
            with tempfile.TemporaryDirectory() as outside:
                (Path(root) / "pilot").symlink_to(
                    Path(outside), target_is_directory=True
                )
                result = exchange(root, [request(1, "session/prompt")])
                reply = json.loads(result.stdout)
                self.assertEqual(reply["error"]["code"], -32000)
                self.assertEqual(list(Path(outside).iterdir()), [])



if __name__ == "__main__":
    unittest.main()
